-- Enforce: max 6 photos per listing
create or replace function public.enforce_listing_photo_limit()
returns trigger
language plpgsql
as $$
declare
  c integer;
begin
  select count(*) into c from public.listing_photos where listing_id = new.listing_id;
  if c >= 6 then
    raise exception 'photo_limit_exceeded';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_photo_limit on public.listing_photos;
create trigger trg_photo_limit
before insert on public.listing_photos
for each row execute function public.enforce_listing_photo_limit();

-- Enforce: max 5 enquiries/day per student
create or replace function public.enforce_daily_enquiry_limit()
returns trigger
language plpgsql
as $$
declare
  c integer;
  day_start timestamptz := date_trunc('day', now());
  day_end timestamptz := date_trunc('day', now()) + interval '1 day';
begin
  select count(*) into c
  from public.enquiries
  where student_id = new.student_id
    and created_at >= day_start
    and created_at < day_end;

  if c >= 5 then
    raise exception 'daily_limit_exceeded';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_enquiry_rate_limit on public.enquiries;
create trigger trg_enquiry_rate_limit
before insert on public.enquiries
for each row execute function public.enforce_daily_enquiry_limit();

