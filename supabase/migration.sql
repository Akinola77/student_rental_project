-- Extensions
create extension if not exists "pgcrypto";

-- Enums (as CHECK constraints to keep it simple for PostgREST)

-- Universities
create table if not exists public.universities (
  id smallint generated by default as identity primary key,
  name text not null unique
);

-- Profiles (1:1 with auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('student','landlord','admin')),
  email text not null,
  full_name text,

  -- student fields
  university_id smallint references public.universities(id),
  budget_min integer check (budget_min is null or budget_min >= 0),
  budget_max integer check (budget_max is null or budget_max >= 0),
  move_in_date date,

  -- landlord fields
  phone text,
  verification_status text check (verification_status is null or verification_status in ('pending','approved','rejected','suspended')),
  verified_at timestamptz,

  -- admin/user mgmt
  account_status text not null default 'active' check (account_status in ('active','suspended','banned')),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Admin-only notes about landlord verification decisions
create table if not exists public.landlord_verification_notes (
  landlord_id uuid primary key references public.profiles(id) on delete cascade,
  notes text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Listings (public fields only; private address is in listing_private)
create table if not exists public.listings (
  id uuid primary key default gen_random_uuid(),
  landlord_id uuid not null references public.profiles(id) on delete cascade,

  title text not null,
  city text not null default 'Dublin' check (city = 'Dublin'),
  university_id smallint not null references public.universities(id),

  rent_monthly_eur integer not null check (rent_monthly_eur > 0),
  deposit_eur integer not null check (deposit_eur >= 0),
  bills_included boolean not null default false,

  room_type text not null check (room_type in ('single_room','shared_room','entire_property')),
  available_from date not null,
  min_stay text not null check (min_stay in ('short_term','semester','academic_year')),

  description text not null,
  house_rules text,

  status text not null default 'draft' check (status in ('draft','pending_review','active','under_offer','let','deactivated')),
  moderation_notes text,

  -- denormalized for public badge (avoids exposing profile fields)
  landlord_verified boolean not null default false,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.listing_private (
  listing_id uuid primary key references public.listings(id) on delete cascade,
  address text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.listing_photos (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  storage_path text not null,
  sort_order smallint not null check (sort_order >= 1 and sort_order <= 6),
  created_at timestamptz not null default now(),
  unique (listing_id, sort_order)
);

create table if not exists public.enquiries (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  move_in_date date,
  length_of_stay text,
  message text not null,
  status text not null default 'open' check (status in ('open','closed')),
  created_at timestamptz not null default now()
);

create table if not exists public.enquiry_messages (
  id uuid primary key default gen_random_uuid(),
  enquiry_id uuid not null references public.enquiries(id) on delete cascade,
  sender_role text not null check (sender_role in ('student','landlord','admin')),
  sender_id uuid not null references public.profiles(id) on delete cascade,
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.landlord_verification_docs (
  id uuid primary key default gen_random_uuid(),
  landlord_id uuid not null references public.profiles(id) on delete cascade,
  doc_type text not null check (doc_type in ('government_id','proof_of_ownership')),
  storage_path text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.listing_reports (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  reason text not null check (reason in ('asked_for_money_upfront','suspicious_communication','fake_photos','too_good_to_be_true','other')),
  details text,
  status text not null default 'open' check (status in ('open','resolved')),
  resolved_at timestamptz,
  resolved_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigserial primary key,
  actor_id uuid references public.profiles(id),
  action text not null,
  entity_type text not null,
  entity_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

