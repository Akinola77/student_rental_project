-- Keep listings.landlord_verified in sync with profiles.verification_status
create or replace function public.sync_landlord_verified_to_listings()
returns trigger
language plpgsql
as $$
begin
  if new.role = 'landlord' then
    update public.listings
      set landlord_verified = (new.verification_status = 'approved')
    where landlord_id = new.id;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_sync_landlord_verified on public.profiles;
create trigger trg_sync_landlord_verified
after update of verification_status on public.profiles
for each row execute function public.sync_landlord_verified_to_listings();

create or replace function public.set_listing_landlord_verified_on_insert()
returns trigger
language plpgsql
as $$
declare
  vs text;
begin
  select verification_status into vs from public.profiles where id = new.landlord_id;
  new.landlord_verified = (vs = 'approved');
  return new;
end;
$$;

drop trigger if exists trg_set_listing_landlord_verified on public.listings;
create trigger trg_set_listing_landlord_verified
before insert on public.listings
for each row execute function public.set_listing_landlord_verified_on_insert();

-- Listing status transition guards (MVP)
create or replace function public.guard_listing_status()
returns trigger
language plpgsql
as $$
declare
  is_admin boolean;
  landlord_status text;
begin
  -- Determine admin by profiles table (RLS-safe: this runs inside DB with current JWT)
  select (auth.role() = 'service_role') or exists(
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.role = 'admin'
      and p.account_status = 'active'
  ) into is_admin;

  if new.status = 'active' and not is_admin then
    raise exception 'only_admin_can_activate';
  end if;

  if new.status = 'pending_review' then
    select verification_status into landlord_status
    from public.profiles p
    where p.id = new.landlord_id;

    if landlord_status is distinct from 'approved' then
      raise exception 'landlord_not_verified';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_guard_listing_status on public.listings;
create trigger trg_guard_listing_status
before insert or update of status on public.listings
for each row execute function public.guard_listing_status();

